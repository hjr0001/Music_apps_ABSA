import time
import re
import pandas as pd
from tqdm import tqdm
from google_play_scraper import Sort, reviews

TARGET_APPS = {
    "Spotify": "com.spotify.music",
    "YouTube Music": "com.google.android.apps.youtube.music"
}

def scrape_app_reviews(app_id: str, app_name: str, target_count: int = 10000) -> pd.DataFrame:
    scraped_data = []
    continuation_token = None
    batch_size = 200

    pbar = tqdm(total=target_count, desc=f"Fetching {app_name}")

    while len(scraped_data) < target_count:
        count_to_fetch = min(batch_size, target_count - len(scraped_data))

        try:
            batch, continuation_token = reviews(
                app_id,
                lang="en",
                country="us",
                sort=Sort.NEWEST,
                count=count_to_fetch,
                continuation_token=continuation_token
            )

            if not batch:
                break

            for item in batch:
                scraped_data.append({
                    "app_name": app_name,
                    "app_id": app_id,
                    "review_id": item.get("reviewId"),
                    "user_name": item.get("userName"),
                    "content": item.get("content"),
                    "score": item.get("score"),
                    "thumbs_up_count": item.get("thumbsUpCount", 0),
                    "review_created_version": item.get("reviewCreatedVersion"),
                    "created_at": item.get("at")
                })

            pbar.update(len(batch))

            if not continuation_token:
                break

            time.sleep(0.3)

        except Exception as e:
            print(f"\nError scraping {app_name}: {e}")
            break

    pbar.close()
    return pd.DataFrame(scraped_data)

# Run scraping
datasets = []
for name, package_id in TARGET_APPS.items():
    df_app = scrape_app_reviews(package_id, name, target_count=10000)
    datasets.append(df_app)

df_raw = pd.concat(datasets, ignore_index=True)
print(f"Total raw reviews collected: {len(df_raw)}")

print(df_raw.head(10))

import re

def clean_review_text(text: str) -> str:
    if not isinstance(text, str):
        return ""

    # Strip URL links and HTML tags
    text = re.sub(r"http\S+|www\S+|<.*?>", "", text)

    # Remove excessive repeated punctuation (e.g., "slow!!!!!!" -> "slow!")
    text = re.sub(r"([!?.,])\1+", r"\1", text)

    # Normalize excessive whitespace
    text = re.sub(r"\s+", " ", text).strip()
    return text

def preprocess_dataset(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()

    # 1. Deduplicate by review ID
    df = df.drop_duplicates(subset=["review_id"])

    # 2. Clean text content
    df["clean_text"] = df["content"].apply(clean_review_text)

    # 3. Filter by word count: reviews under 5 words rarely contain extractable aspects
    df["word_count"] = df["clean_text"].apply(lambda x: len(x.split()))
    df = df[df["word_count"] >= 5]

    # 4. Standardize datetime
    df["created_at"] = pd.to_datetime(df["created_at"])
    df["date"] = df["created_at"].dt.date

    return df.reset_index(drop=True)

df_clean = preprocess_dataset(df_raw)
print(f"Substantive reviews retained after filtering: {len(df_clean)}")

df_clean.to_parquet("competitor_app_reviews.parquet", index=False)