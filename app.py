import streamlit as st
import pandas as pd
import plotly.express as px
import plotly.graph_objects as go

st.set_page_config(
    page_title="Spotify vs. YouTube Music | ABSA Stakeholder Dashboard",
    page_icon="🎧",
    layout="wide"
)

@st.cache_data
def load_data():
    df = pd.read_parquet("absa_stakeholder_results.parquet")
    summary = pd.read_csv("stakeholder_aspect_comparison.csv")
    return df, summary

st.title("🎧 Spotify vs. YouTube Music: Aspect-Based Sentiment Analysis")
st.markdown("Executive comparison of Google Play Store user reviews across core product aspects.")

try:
    df, summary = load_data()
except FileNotFoundError:
    st.error("Please ensure `absa_stakeholder_results.parquet` and `stakeholder_aspect_comparison.csv` are generated by running data_preprocessing.py, absa_engine.py, and stakeholder_metrics.py first.")
    st.stop()

# --- TOP KPI ROW ---
col1, col2, col3, col4 = st.columns(4)
spotify_df = df[df["app_name"] == "Spotify"]
ytm_df = df[df["app_name"] == "YouTube Music"]

col1.metric("Spotify Aspect Mentions", f"{len(spotify_df):,}")
col2.metric(
    "Spotify Net Sentiment (NSS)",
    f"{((spotify_df['sentiment'] == 'Positive').mean() - (spotify_df['sentiment'] == 'Negative').mean()) * 100:.1f}%"
)
col3.metric("YouTube Music Aspect Mentions", f"{len(ytm_df):,}")
col4.metric(
    "YouTube Music Net Sentiment (NSS)",
    f"{((ytm_df['sentiment'] == 'Positive').mean() - (ytm_df['sentiment'] == 'Negative').mean()) * 100:.1f}%"
)

st.divider()

# --- ROW 1: NET SENTIMENT BAR CHART & RADAR CHART ---
left_col, right_col = st.columns([3, 2])

with left_col:
    st.subheader("📊 Net Sentiment Score (NSS) by Aspect")
    fig_nss = px.bar(
        summary,
        x="net_sentiment_score",
        y="aspect_category",
        color="app_name",
        barmode="group",
        orientation="h",
        color_discrete_map={"Spotify": "#1DB954", "YouTube Music": "#FF0000"},
        labels={"net_sentiment_score": "Net Sentiment (% Pos - % Neg)", "aspect_category": "Product Aspect"},
        text="net_sentiment_score"
    )
    fig_nss.update_traces(texttemplate="%{text}%", textposition="outside")
    fig_nss.update_layout(xaxis_range=[-100, 100], height=450)
    st.plotly_chart(fig_nss, use_container_width=True)

with right_col:
    st.subheader("🕸️ Competitive Positive Sentiment Radar")
    fig_radar = go.Figure()
    for app, color in [("Spotify", "#1DB954"), ("YouTube Music", "#FF0000")]:
        app_sub = summary[summary["app_name"] == app]
        fig_radar.add_trace(go.Scatterpolar(
            r=app_sub["pct_positive"],
            theta=app_sub["aspect_category"],
            fill="toself",
            name=app,
            line_color=color
        ))
    fig_radar.update_layout(
        polar=dict(radialaxis=dict(visible=True, range=[0, 100])),
        showlegend=True,
        height=450
    )
    st.plotly_chart(fig_radar, use_container_width=True)

st.divider()

# --- ROW 2: SENTIMENT DISTRIBUTION STACKED BAR ---
st.subheader("📈 Granular Sentiment Breakdown (% Positive / Neutral / Negative)")
melted = summary.melt(
    id_vars=["app_name", "aspect_category"],
    value_vars=["pct_positive", "pct_neutral", "pct_negative"],
    var_name="Polarity",
    value_name="Percentage"
)
melted["Polarity"] = melted["Polarity"].map({
    "pct_positive": "Positive",
    "pct_neutral": "Neutral",
    "pct_negative": "Negative"
})

fig_stack = px.bar(
    melted,
    x="Percentage",
    y="aspect_category",
    color="Polarity",
    facet_col="app_name",
    orientation="h",
    color_discrete_map={"Positive": "#2ecc71", "Neutral": "#95a5a6", "Negative": "#e74c3c"},
    text="Percentage"
)
fig_stack.update_traces(texttemplate="%{text:.1f}%", textposition="inside")
st.plotly_chart(fig_stack, use_container_width=True)

st.divider()

# --- ROW 3: VOICE OF THE CUSTOMER (VoC) EXPLORER ---
st.subheader("💬 Voice of the Customer (VoC) Evidence Explorer")
f_col1, f_col2, f_col3 = st.columns(3)

selected_app = f_col1.selectbox("Select App", options=["Spotify", "YouTube Music"])
selected_aspect = f_col2.selectbox("Select Aspect", options=summary["aspect_category"].unique())
selected_sentiment = f_col3.selectbox("Select Sentiment", options=["Negative", "Positive", "Neutral"])

filtered_quotes = df[
    (df["app_name"] == selected_app) &
    (df["aspect_category"] == selected_aspect) &
    (df["sentiment"] == selected_sentiment)
].sort_values(by="confidence", ascending=False)

st.dataframe(
    filtered_quotes[["clause", "full_review", "sentiment", "confidence", "sentiment_score"]].head(25),
    use_container_width=True,
    hide_index=True
)
